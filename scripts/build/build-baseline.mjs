/**
 * Bake the baseline day into src/data/baseline.json.
 *
 * The Results panel compares the live (possibly scenario-modified) day against
 * a deterministic no-lever day. It also compares *mid-day*: a 10:30 live run
 * must be judged against the baseline at 10:30, not against the finished
 * baseline day — so we snapshot cumulative metrics every 10 sim-minutes.
 *
 * The cohort size and seed MUST match App.tsx's createMind call.
 *
 * Run: node scripts/build/build-baseline.mjs
 */
import fs from 'node:fs'
import assert from 'node:assert/strict'
import { createMind, DAY_END } from '../../src/engine/mind/engine.ts'

const mind = createMind({ seed: 21, cohort: 420 })
const t0 = Date.now()

/* cumulative snapshot every 10 minutes, so live deltas are time-honest */
const by10 = []
for (let t = 10; t <= DAY_END; t += 10) {
  mind.runTo(t)
  const m = mind.metrics()
  by10.push({
    meals: Object.values(m.meals).reduce((a, b) => a + b, 0),
    mealsBy: { ...m.meals },
    revenue: m.revenueCents,
    walk: m.walkMinutes,
    att: m.classesAttended,
    late: m.classesLate,
    miss: m.classesMissed,
    ev: m.eventAttendees,
    stress: Number(m.stressAvg.toFixed(2)),
  })
}

const m = mind.metrics()
assert.ok(m.moneyCheck, 'baseline must conserve money')
assert.ok(m.classesAttended > 300, 'a baseline day must contain real attendance')
assert.ok(by10.length === DAY_END / 10, `expected ${DAY_END / 10} buckets, got ${by10.length}`)

const out = {
  _comment:
    'generated by scripts/build/build-baseline.mjs — the unmodified Tuesday for the 420-student focus cohort. by10 = cumulative totals at each 10-minute mark.',
  final: {
    meals: m.meals,
    queueMinutes: m.queueMinutes,
    revenueCents: m.revenueCents,
    walkMinutes: m.walkMinutes,
    classesAttended: m.classesAttended,
    classesLate: m.classesLate,
    classesMissed: m.classesMissed,
    eventAttendees: m.eventAttendees,
    stressAvg: Number(m.stressAvg.toFixed(2)),
  },
  by10,
}

fs.writeFileSync(
  new URL('../../src/data/baseline.json', import.meta.url),
  JSON.stringify(out, null, 2) + '\n',
)
console.log(`baseline baked in ${((Date.now() - t0) / 1000).toFixed(1)}s — ${by10.length} buckets`)
console.log(JSON.stringify(out.final))
